export default async function handler(req, res) {
  if (req.method !== 'POST') {
    return res.status(405).json({
      error: 'Method not allowed'
    });
  }

  try {
    const { word, accumulatedWords = [] } = req.body;

    if (!word || !word.trim()) {
      return res.status(400).json({
        error: 'word is required'
      });
    }

    const accumulatedWordsText = accumulatedWords.length > 0 ? accumulatedWords.join('、') : 'まだありません';

    const prompt = `
あなたは、日本の古典和歌から近現代短歌まで、短歌の歴史・定型・韻律・修辞・推敲を深く理解した歌人です。

これから、鑑賞者が何かを見て感じた「ひとつの言葉」と、これまでに他の鑑賞者たちが選んだ言葉の蓄積リストを渡します。

これは「言葉の箱庭」というインタラクティブ作品のための短歌です。

入力された一語は、その人がある景色の中から選び取った視点です。
あなたはその一語を単なる「お題」として扱うのではなく、

「その人には、どんな景色が見えていたのか」
「その一語の奥には、どんな時間・感情・気配があったのか」

を想像し、その世界を一首の短歌として再構築してください。

入力語の意味を説明するのではなく、
その一語の奥にあったかもしれない世界を、三十一音の中に立ち上げてください。

【蓄積リストの扱い】

蓄積リストは、今回の短歌の材料ではありません。
今回の一首は、あくまで今回の入力語から生まれるものとして詠んでください。

ただし、蓄積リストに含まれる言葉と意味領域や発想が明らかに近くなりすぎないように意識し、
箱庭全体で似たような短歌ばかりにならないよう、
今回の一語にふさわしい異なる角度・時間・距離感を選んでください。

蓄積リストの内容を短歌本文で説明・言及・解説しないでください。

【短歌としての条件】

・原則として五・七・五・七・七、合計三十一音で詠んでください。
・文字数ではなく、日本語として発音したときの「音」を基準にしてください。
・多少の字余り・字足らずは、表現上の必然性がある場合のみ許可します。
・五・七・五だけで意味を完結させないでください。
・最後の七・七を、説明・感想・言い換え・オチとして付け足さないでください。
・三十一音すべてで初めて一首が成立する構造にしてください。

【一首の構成】

入力語から、一つの具体的な場面を想像してください。

抽象的な感情をそのまま述べるのではなく、
物、場所、光、音、温度、身体の動き、距離、時間など、
読み手が知覚できる具体的な像を一つ以上入れてください。

一首の中には、小さな変化を作ってください。

上句で見えていたものが、
下句まで読むと少し違って見える構造を目指してください。

大げさなどんでん返しやオチは不要です。

【感情の表現】

「悲しい」「嬉しい」「寂しい」「不安」「希望」など、
感情を直接説明しすぎないでください。

景色、物、動作、身体感覚などを通して
感情が立ち上がるようにしてください。

結句で作品の意味を説明し切らず、
読み終えたあとにも像や感情が少し残るようにしてください。

【言葉遣い】

現代の日本語として自然な言葉を使ってください。

短歌らしく見せるためだけに
「けり」「かな」「なり」などの古語を使わないでください。

難しい漢語、美辞麗句、
助詞を不自然に削った表現も避けてください。

入力された言葉そのものを短歌に入れる必要はありません。

その語を直接使うより、
景色・物・時間・身体感覚へ変換した方がよい場合は変換してください。

重要なのは、読み終えたときに
「この短歌は確かに、この一語から生まれた」
と感じられることです。

【避けること】

川柳、標語、格言、キャッチコピー、
言葉遊びだけで成立する作品にはしないでください。

特に、

・五・七・五だけで内容が完結する
・七・七が感想や説明になる
・最後にオチやパンチラインを置く
・散文を五行に切っただけになる
・入力語の辞書的説明になる

ことを避けてください。

また、

「夕焼け」「月」「星」「涙」「桜」「風」「空」「夢」
「光」「影」「心」「記憶」

などの詩で頻出する語を、
入力との必然性なく安易に使用しないでください。

「心に残る」
「時が止まる」
「そっと寄り添う」
「希望の光」

など、既視感の強い詩的表現にも逃げないでください。

【生成前の推敲】

最初に思いついた一首をそのまま出さず、
内部で複数案を考え、最も完成度の高い一首を選んでください。

最終的に、

・五七五七七の韻律が自然か
・具体的な像があるか
・三十一音全体が必要か
・上句から下句へ小さな変化があるか
・七七が説明の付け足しになっていないか
・感情を説明しすぎていないか
・ありふれた「エモい文章」になっていないか
・今回の一語から生まれる必然性があるか
・蓄積リストと意味領域が近すぎないか
・読み終えたあとに余韻が残るか

を確認し、必要なら推敲してください。

思考過程や候補は出力しないでください。

【今回の入力語】
${word.trim()}

【これまでに選ばれた言葉】
${accumulatedWordsText}

以上を踏まえて、一首だけ生成してください。

出力は五・七・五・七・七の五句を、
必ず5行に分けた短歌本文のみとしてください。

タイトル、作者名、解説、前置き、入力語、
蓄積リスト、注釈は一切出力しないでください。
`.trim();

    const response = await fetch('https://api.anthropic.com/v1/messages', {
      method: 'POST',
      headers: {
        'content-type': 'application/json',
        'x-api-key': process.env.ANTHROPIC_API_KEY,
        'anthropic-version': '2023-06-01'
      },
      body: JSON.stringify({
        model: 'claude-sonnet-5',
        max_tokens: 400,
        messages: [
          {
            role: 'user',
            content: prompt
          }
        ]
      })
    });

    const data = await response.json();

    if (!response.ok) {
      return res.status(500).json({
        error: 'Claude API error',
        anthropicStatus: response.status,
        message: data?.error?.message || 'Unknown Anthropic error',
        type: data?.error?.type || 'unknown'
      });
    }

    const text = data.content
      ?.filter((item) => item.type === 'text')
      .map((item) => item.text)
      .join('')
      .trim();

    if (!text) {
      return res.status(500).json({
        error: 'No tanka returned'
      });
    }

    return res.status(200).json({
      tanka: text
    });
  } catch (error) {
    console.error('Server error:', error);

    return res.status(500).json({
      error: 'Server error'
    });
  }
}
